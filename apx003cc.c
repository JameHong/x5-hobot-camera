/* Write registers up to 4 at a time */
static int apx003_hvs_write_reg(struct i2c_client *client, u16 reg,
			    u32 len, u32 val)
{
	u32 buf_i, val_i;
	u8 buf[6];
	u8 *val_p;
	__be32 val_be;

	if (len > 4)
		return -EINVAL;

	buf[0] = reg >> 8;
	buf[1] = reg & 0xff;

	val_be = cpu_to_be32(val);
	val_p = (u8 *)&val_be;
	buf_i = 2;
	val_i = 4 - len;

	while (val_i < 4)
		buf[buf_i++] = val_p[val_i++];

	if (i2c_master_send(client, buf, len + 2) != len + 2) {
		dev_err(&client->dev, "Failed to write 0x%04x,0x%x\n", reg, val);
		return -EIO;
	}
	return 0;
}

static int apx003_hvs_write_array(struct i2c_client *client,
			       const struct regval *regs)
{
	u32 i;
	int ret = 0;

	for (i = 0; ret == 0 && regs[i].addr != REG_NULL; i++) {
		if(regs[i].addr == REG_DELAY) {
			
			usleep_range(1000 * regs[i].val, 1000 * regs[i].val);
		} else {
			ret |= apx003_hvs_write_reg(client, regs[i].addr,
				OV50C40_REG_VALUE_08BIT, regs[i].val);
		}

	}
	return ret;
}

/* Read registers up to 4 at a time */
static int apx003_hvs_read_reg(struct i2c_client *client,
			    u16 reg,
			    unsigned int len,
			    u32 *val)
{
	struct i2c_msg msgs[2];
	u8 *data_be_p;
	__be32 data_be = 0;
	__be16 reg_addr_be = cpu_to_be16(reg);
	int ret;

	if (len > 4 || !len)
		return -EINVAL;

	data_be_p = (u8 *)&data_be;
	/* Write register address */
	msgs[0].addr = client->addr;
	msgs[0].flags = 0;
	msgs[0].len = 2;
	msgs[0].buf = (u8 *)&reg_addr_be;

	/* Read data from register */
	msgs[1].addr = client->addr;
	msgs[1].flags = I2C_M_RD;
	msgs[1].len = len;
	msgs[1].buf = &data_be_p[4 - len];

	ret = i2c_transfer(client->adapter, msgs, ARRAY_SIZE(msgs));
	if (ret != ARRAY_SIZE(msgs))
		return -EIO;

	*val = be32_to_cpu(data_be);

	return 0;
}

static int apx003_hvs_get_reso_dist(const struct apx003_hvs_mode *mode,
				struct v4l2_mbus_framefmt *framefmt)
{
	return abs(mode->width - framefmt->width) +
	       abs(mode->height - framefmt->height);
}

static const struct apx003_hvs_mode *
apx003_hvs_find_best_fit(struct apx003_hvs *apx003_hvs, struct v4l2_subdev_format *fmt)
{
	struct v4l2_mbus_framefmt *framefmt = &fmt->format;
	int dist;
	int cur_best_fit = 0;
	int cur_best_fit_dist = -1;
	unsigned int i;

	for (i = 0; i < apx003_hvs->cfg_num; i++) {
		dist = apx003_hvs_get_reso_dist(&apx003_hvs->support_modes[i], framefmt);
		if ((cur_best_fit_dist == -1 || dist < cur_best_fit_dist) &&
			(apx003_hvs->support_modes[i].bus_fmt == framefmt->code)) {
			cur_best_fit_dist = dist;
			cur_best_fit = i;
		}
	}
	dev_info(&apx003_hvs->client->dev, "%s: cur_best_fit(%d)",
		 __func__, cur_best_fit);
	return &apx003_hvs->support_modes[cur_best_fit];
}

static int apx003_hvs_set_fmt(struct v4l2_subdev *sd,
			  struct v4l2_subdev_pad_config *cfg,
			  struct v4l2_subdev_format *fmt)
{
	struct apx003_hvs *apx003_hvs = to_apx003_hvs(sd);
	const struct apx003_hvs_mode *mode;
	s64 vblank_def;
	u64 pixel_rate = 0;
	//u32 lane_num = apx003_hvs->bus_cfg.bus.mipi_csi2.num_data_lanes;
	u32 lane_num = MIPI_LANE_NUM;

	mutex_lock(&apx003_hvs->mutex);

	mode = apx003_hvs_find_best_fit(apx003_hvs, fmt);
	fmt->format.code = mode->bus_fmt;
	fmt->format.width = mode->width;
	fmt->format.height = mode->height;
	fmt->format.field = V4L2_FIELD_NONE;
	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
#ifdef CONFIG_VIDEO_V4L2_SUBDEV_API
		*v4l2_subdev_get_try_format(sd, cfg, fmt->pad) = fmt->format;
#else
		mutex_unlock(&apx003_hvs->mutex);
		return -ENOTTY;
#endif
	} else {
		apx003_hvs->cur_mode = mode;
//		h_blank = mode->hts_def - mode->width;
//		__v4l2_ctrl_modify_range(apx003_hvs->hblank, h_blank,
//					 h_blank, 1, h_blank);
//		vblank_def = mode->vts_def - mode->height;
//		__v4l2_ctrl_modify_range(apx003_hvs->vblank, vblank_def,
//					 OV50C40_VTS_MAX - mode->height,
//					 1, vblank_def);
		__v4l2_ctrl_s_ctrl(apx003_hvs->vblank, vblank_def);
		pixel_rate = (u32)link_freq_items[mode->mipi_freq_idx] / mode->bpp * 2 * lane_num;
		__v4l2_ctrl_s_ctrl_int64(apx003_hvs->pixel_rate,
					 pixel_rate);
		__v4l2_ctrl_s_ctrl(apx003_hvs->link_freq,
				   mode->mipi_freq_idx);
	}
	dev_info(&apx003_hvs->client->dev, "%s: mode->mipi_freq_idx(%d)",
		 __func__, mode->mipi_freq_idx);

	mutex_unlock(&apx003_hvs->mutex);

	return 0;
}

