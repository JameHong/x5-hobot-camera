static int apx003_hvs_s_stream(struct v4l2_subdev *sd, int on)
{
	struct apx003_hvs *apx003_hvs = to_apx003_hvs(sd);
	struct i2c_client *client = apx003_hvs->client;
	int ret = 0;

//	dev_info(&client->dev, "%s: on: %d, %dx%d@%d\n", __func__, on,
//				apx003_hvs->cur_mode->width,
//				apx003_hvs->cur_mode->height,
//		DIV_ROUND_CLOSEST(apx003_hvs->cur_mode->max_fps.denominator,
//				  apx003_hvs->cur_mode->max_fps.numerator));

	mutex_lock(&apx003_hvs->mutex);
	on = !!on;
	if (on == apx003_hvs->streaming)
		goto unlock_and_return;

	if (on) {
		if (apx003_hvs->is_thunderboot && rkisp_tb_get_state() == RKISP_TB_NG) {
			apx003_hvs->is_thunderboot = false;
			__apx003_hvs_power_on(apx003_hvs);
		}
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		ret = __apx003_hvs_start_stream(apx003_hvs);
		if (ret) {
			v4l2_err(sd, "start stream failed while write regs\n");
			pm_runtime_put(&client->dev);
			goto unlock_and_return;
		}
	} else {
		__apx003_hvs_stop_stream(apx003_hvs);
		pm_runtime_put(&client->dev);
	}

	apx003_hvs->streaming = on;

unlock_and_return:
	mutex_unlock(&apx003_hvs->mutex);

	return ret;
}

static int apx003_hvs_s_power(struct v4l2_subdev *sd, int on)
{
	struct apx003_hvs *apx003_hvs = to_apx003_hvs(sd);
	struct i2c_client *client = apx003_hvs->client;
	int ret = 0;

	mutex_lock(&apx003_hvs->mutex);

	/* If the power state is not modified - no work to do. */
	if (apx003_hvs->power_on == !!on)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		if (!apx003_hvs->is_thunderboot) {
			//ret |= apx003_hvs_write_reg(apx003_hvs->client,OV50C40_SOFTWARE_RESET_REG,OV50C40_REG_VALUE_08BIT,0x01);
			ret |= apx003_hvs_write_array(apx003_hvs->client,apx003cc_aps_global_regs);
			usleep_range(100, 200);
		}

		apx003_hvs->power_on = true;
	} else {
		pm_runtime_put(&client->dev);
		apx003_hvs->power_on = false;
	}

unlock_and_return:
	mutex_unlock(&apx003_hvs->mutex);

	return ret;
}

